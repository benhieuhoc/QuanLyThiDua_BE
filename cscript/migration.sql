ALTER TABLE point ADD COLUMN IF NOT EXISTS accountid integer
    CONSTRAINT fk_point_account REFERENCES account (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS point_week_class_idx ON point (weekid, classid);

-- Học sinh vi phạm / được nêu trong lượt chấm (1 lượt gắn nhiều học sinh cùng lớp)
-- Xóa lượt chấm thì xóa luôn liên kết; xóa học sinh đã có liên kết bị chặn ở service (409)
CREATE TABLE IF NOT EXISTS point_student
(
    pointid integer NOT NULL,
    studentid integer NOT NULL,
    CONSTRAINT point_student_pkey PRIMARY KEY (pointid, studentid),
    CONSTRAINT fk_point_student_point FOREIGN KEY (pointid)
        REFERENCES point (id) ON DELETE CASCADE,
    CONSTRAINT fk_point_student_student FOREIGN KEY (studentid)
        REFERENCES student (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS point_student_student_idx ON point_student (studentid);

-- Điểm tuần của mỗi lớp: điểm = điểm gốc + tổng các lượt cộng/trừ của phần đó
-- *_minus là tổng điểm trừ (số dương), *_plus là tổng điểm cộng
CREATE OR REPLACE VIEW score_view AS
SELECT w.id AS weekid, w.schoolyearid, w.numweek, w.locked,
       cv.id AS classid, cv.name AS classname, cv.gradeid, cv.numgrade, cv.branchid, cv.branchcode, cv.seq,
       cv.teacherid, cv.teachername,
       w.conduct_base,
       COALESCE(SUM(p.value) FILTER (WHERE p.type = 'Nề nếp' AND p.value > 0), 0)::int AS conduct_plus,
       COALESCE(-SUM(p.value) FILTER (WHERE p.type = 'Nề nếp' AND p.value < 0), 0)::int AS conduct_minus,
       (w.conduct_base + COALESCE(SUM(p.value) FILTER (WHERE p.type = 'Nề nếp'), 0))::int AS conduct_score,
       w.study_base,
       COALESCE(SUM(p.value) FILTER (WHERE p.type = 'Học tập' AND p.value > 0), 0)::int AS study_plus,
       COALESCE(-SUM(p.value) FILTER (WHERE p.type = 'Học tập' AND p.value < 0), 0)::int AS study_minus,
       (w.study_base + COALESCE(SUM(p.value) FILTER (WHERE p.type = 'Học tập'), 0))::int AS study_score,
       (w.conduct_base + w.study_base + COALESCE(SUM(p.value), 0))::int AS total,
       COUNT(p.id)::int AS entries
FROM week w
CROSS JOIN class_view cv
LEFT JOIN point p ON p.weekid = w.id AND p.classid = cv.id
GROUP BY w.id, cv.id, cv.name, cv.gradeid, cv.numgrade, cv.branchid, cv.branchcode, cv.seq, cv.teacherid, cv.teachername;

