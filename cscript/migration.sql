CREATE TABLE IF NOT EXISTS branch
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name character varying(100) NOT NULL,          -- "Phân hiệu 1"
    code character(1) NOT NULL,                    -- 'A', 'B'
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT branch_pkey PRIMARY KEY (id),
    CONSTRAINT branch_code_unique UNIQUE (code),
    CONSTRAINT branch_code_check CHECK (code ~ '^[A-Z]$')
);

CREATE TABLE IF NOT EXISTS teacher
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,   -- bỏ khai báo PK trùng
    name character varying(25),
    branchid integer NOT NULL,
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT teacher_pkey PRIMARY KEY (id),
    CONSTRAINT fk_teacher_branch FOREIGN KEY (branchid)
        REFERENCES branch (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS grade 
(
	id INTEGER GENERATED BY DEFAULT AS IDENTITY,
	numgrade integer NOT NULL,
	CONSTRAINT grade_pkey PRIMARY KEY (id),
	CONSTRAINT grade_numgrade_unique UNIQUE (numgrade)
);

CREATE TABLE IF NOT EXISTS class
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,   -- đổi sang identity
    seq integer NOT NULL CHECK (seq > 0),          -- số thứ tự: 1, 2, ...
    gradeid integer NOT NULL,
    branchid integer NOT NULL,
    teacherid integer,                             -- GVCN, null = chưa phân công
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT class_pkey PRIMARY KEY (id),
    CONSTRAINT class_unique UNIQUE (gradeid, branchid, seq),
    CONSTRAINT class_teacher_unique UNIQUE (teacherid),  -- 1 GV chủ nhiệm 1 lớp (nhiều lớp null vẫn hợp lệ)
    CONSTRAINT fk_class_grade  FOREIGN KEY (gradeid)  REFERENCES grade (id)  ON DELETE CASCADE,
    CONSTRAINT fk_class_branch FOREIGN KEY (branchid) REFERENCES branch (id) ON DELETE CASCADE,
    CONSTRAINT fk_class_teacher FOREIGN KEY (teacherid) REFERENCES teacher (id) ON DELETE CASCADE
);

-- Tên lớp = khối + mã phân hiệu + số thứ tự (vd: 6A1), không lưu cứng trong bảng class
-- LEFT JOIN teacher: lớp chưa có GVCN thì teacherid, teachername là null
CREATE OR REPLACE VIEW class_view AS
SELECT c.*, g.numgrade, b.code AS branchcode, b.name AS branchname, t.name AS teachername,
       g.numgrade::text || b.code || c.seq::text AS name
FROM class c
JOIN grade g   ON g.id = c.gradeid
JOIN branch b  ON b.id = c.branchid
LEFT JOIN teacher t ON t.id = c.teacherid;


-- Học sinh: thuộc đúng 1 lớp, chuyển lớp bằng cách đổi classid
CREATE TABLE IF NOT EXISTS student
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    code character varying(20) NOT NULL,           -- mã học sinh theo hồ sơ của Sở (vd 2609138407)
    name character varying(50) NOT NULL,
    gender character varying(3),                   -- 'Nam', 'Nữ' (không bắt buộc)
    birthdate date,
    classid integer NOT NULL,
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT student_pkey PRIMARY KEY (id),
    CONSTRAINT student_code_unique UNIQUE (code),
    CONSTRAINT fk_student_class FOREIGN KEY (classid)
        REFERENCES class (id) ON DELETE CASCADE,
    CONSTRAINT student_gender_check CHECK (gender::text = ANY (
		ARRAY[
			'Nam'::character varying,
			'Nữ'::character varying
		]::text[]
	))
);

CREATE INDEX IF NOT EXISTS student_class_idx ON student (classid);

-- Tài khoản đăng nhập: chỉ 2 role
--   admin: giáo viên quản lý nề nếp (có thể gắn teacherid để hiển thị tên), toàn quyền
--   user : giáo viên chủ nhiệm (gắn teacherid) hoặc cờ đỏ (gắn studentid), mỗi tài khoản user gắn đúng 1 trong 2
-- password lưu hash bcrypt (60 ký tự), không lưu mật khẩu thô
CREATE TABLE IF NOT EXISTS account
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    username character varying(50) NOT NULL,
    password character varying(60) NOT NULL,
    role character varying(10) NOT NULL,
    teacherid integer,                             -- GVCN / admin là giáo viên
    studentid integer,                             -- cờ đỏ
    active boolean NOT NULL DEFAULT true,          -- false = khóa tài khoản (vd cờ đỏ hết nhiệm kỳ)
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT account_pkey PRIMARY KEY (id),
    CONSTRAINT account_username_unique UNIQUE (username),
    CONSTRAINT account_teacher_unique UNIQUE (teacherid),  -- 1 giáo viên tối đa 1 tài khoản
    CONSTRAINT account_student_unique UNIQUE (studentid),  -- 1 học sinh tối đa 1 tài khoản
    CONSTRAINT fk_account_teacher FOREIGN KEY (teacherid)
        REFERENCES teacher (id) ON DELETE CASCADE,
    CONSTRAINT fk_account_student FOREIGN KEY (studentid)
        REFERENCES student (id) ON DELETE CASCADE,
    CONSTRAINT account_role_check CHECK (role::text = ANY (
		ARRAY[
			'admin'::character varying,
			'user'::character varying
		]::text[]
	)),
    -- admin không gắn học sinh; user gắn đúng 1 giáo viên hoặc 1 học sinh
    CONSTRAINT account_owner_check CHECK (
        (role = 'admin' AND studentid IS NULL)
        OR (role = 'user' AND num_nonnulls(teacherid, studentid) = 1)
    )
);

-- Lớp mà tài khoản cờ đỏ được admin phân công chấm điểm
-- (chỉ dùng cho tài khoản có studentid; kiểm tra ở service, không chấm lớp của chính mình)
CREATE TABLE IF NOT EXISTS account_class
(
    accountid integer NOT NULL,
    classid integer NOT NULL,
    created_at date DEFAULT NOW(),
    CONSTRAINT account_class_pkey PRIMARY KEY (accountid, classid),
    CONSTRAINT fk_account_class_account FOREIGN KEY (accountid)
        REFERENCES account (id) ON DELETE CASCADE,
    CONSTRAINT fk_account_class_class FOREIGN KEY (classid)
        REFERENCES class (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS account_class_class_idx ON account_class (classid);

-- Năm học: tạo năm học thì hệ thống tự sinh các tuần 1..N liên tiếp từ startdate
CREATE TABLE IF NOT EXISTS school_year
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name character varying(9) NOT NULL,            -- "2026-2027"
    startdate date NOT NULL,                       -- ngày bắt đầu tuần 1
    semester2_week integer CHECK (semester2_week > 1),  -- tuần bắt đầu học kỳ 2; null = tuần CEIL(số tuần / 2) + 1
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT school_year_pkey PRIMARY KEY (id),
    CONSTRAINT school_year_name_unique UNIQUE (name)
);

-- Tuần thi đua: mỗi tuần cấp điểm gốc riêng cho Nề nếp và Học tập; tuần đã khóa thì không sửa điểm
CREATE TABLE IF NOT EXISTS week
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    schoolyearid integer NOT NULL,
    numweek integer NOT NULL CHECK (numweek > 0),
    startdate date NOT NULL,
    enddate date NOT NULL,
    conduct_base integer NOT NULL DEFAULT 100 CHECK (conduct_base >= 0),  -- điểm gốc Nề nếp
    study_base integer NOT NULL DEFAULT 100 CHECK (study_base >= 0),      -- điểm gốc Học tập
    locked boolean NOT NULL DEFAULT false,
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT week_pkey PRIMARY KEY (id),
    CONSTRAINT week_unique UNIQUE (schoolyearid, numweek),
    CONSTRAINT week_date_check CHECK (enddate >= startdate),
    CONSTRAINT fk_week_school_year FOREIGN KEY (schoolyearid)
        REFERENCES school_year (id) ON DELETE CASCADE
);

-- Lượt cộng/trừ điểm nhập tự do: value < 0 là trừ, value > 0 là cộng
CREATE TABLE IF NOT EXISTS point
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    weekid integer NOT NULL,
    classid integer NOT NULL,
    type character varying(20) NOT NULL,
    content character varying(255) NOT NULL,       -- "Đi trễ 3 bạn", "Giờ học tốt"
    value integer NOT NULL CHECK (value <> 0),
    accountid integer,                             -- tài khoản nhập lượt chấm; null = nhập trước khi có đăng nhập / tài khoản đã xóa
    created_at date DEFAULT NOW(),
    updated_at date DEFAULT NOW(),
    CONSTRAINT point_pkey PRIMARY KEY (id),
    CONSTRAINT fk_point_week FOREIGN KEY (weekid)
        REFERENCES week (id) ON DELETE CASCADE,
    CONSTRAINT fk_point_account FOREIGN KEY (accountid)
        REFERENCES account (id) ON DELETE SET NULL,  -- xóa tài khoản vẫn giữ lượt chấm
    CONSTRAINT fk_point_class FOREIGN KEY (classid)
        REFERENCES class (id) ON DELETE CASCADE,
    CONSTRAINT point_type_check CHECK (type::text = ANY (
		ARRAY[
			'Nề nếp'::character varying,
			'Học tập'::character varying
		]::text[]
	))
);

